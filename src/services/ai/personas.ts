export function getPersonaById(id: string): Persona | undefined {
  return personas.find((p) => p.id === id)
}

export function buildFullSystemPrompt(persona: Persona): string {
  return `${COMMON_SYSTEM_PROMPT}\n\n---\n\n${persona.systemPrompt}`
}
